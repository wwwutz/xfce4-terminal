#!/bin/sh
# Generate embedded-fonts.h, which terminal-embedded-fonts.c compiles into
# xfce4-terminal, from the font files given as arguments.  Uses only od and sed.
set -e

echo "/* generated by mkembedfont.sh - do not edit */"
n=0
for font in "$@"; do
	echo
	echo "/* ${font##*/} */"
	echo "static const unsigned char embedded_font_$n[] = {"
	od -An -v -tx1 "$font" | sed -e 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g'
	echo "};"
	n=`expr $n + 1`
done

echo
echo "static const struct {"
echo "    const unsigned char *data;"
echo "    size_t size;"
echo "} embedded_fonts[] = {"
n=0
for font in "$@"; do
	echo "    { embedded_font_$n, sizeof(embedded_font_$n) },"
	n=`expr $n + 1`
done
echo "};"
